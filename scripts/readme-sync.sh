#!/usr/bin/env sh
# readme-sync.sh: render README.md's status block from package.json + web/SURFACES.tsv.
# Idempotent: running it twice changes nothing. The README block is a cast; this is the mold.
#   sh scripts/readme-sync.sh          rewrite the block in place
#   sh scripts/readme-sync.sh --check  exit 1 if the block is stale (test.sh runs this)
# npm's "version" lifecycle runs it, so `npm version <x>` folds the new version into the tag commit.
set -eu
_self=$0
case "$_self" in */*) _dir=${_self%/*} ;; *) _dir=. ;; esac
ROOT=$(cd "$_dir/.." && pwd)
README="$ROOT/README.md"
BEGIN='<!-- readme-sync:begin (generated by scripts/readme-sync.sh; edit package.json or web/SURFACES.tsv) -->'
END='<!-- readme-sync:end -->'

[ -f "$ROOT/web/SURFACES.tsv" ] || { echo "readme-sync: web/SURFACES.tsv missing" >&2; exit 2; }
ver=$(sed -n 's/^[[:space:]]*"version":[[:space:]]*"\([^"]*\)".*/\1/p' "$ROOT/package.json" | head -n 1)
[ -n "$ver" ] || { echo "readme-sync: no version in package.json" >&2; exit 2; }

block=$(mktemp); out=$(mktemp)
trap 'rm -f "$block" "$out"' EXIT
{
  echo "$BEGIN"
  echo "**License:** MIT · **Status:** v$ver · **Locales verified:** bash 3.2.57,"
  echo "bash 5.3, zsh 5.9, dash (POSIX), /bin/sh, ksh93 — all against one shared"
  echo "[conformance suite](conformance/)."
  _tab=$(printf '\t')
  grep -v '^#' "$ROOT/web/SURFACES.tsv" | grep -v '^[[:space:]]*$' | {
    _first=1
    while IFS="$_tab" read -r url label what; do
      if [ "$_first" = 1 ]; then echo; echo "**Try it live:**"; echo; _first=0; fi
      echo "- [$label]($url): $what"
    done
  }
  echo "$END"
} > "$block"

grep -qF "$BEGIN" "$README" || { echo "readme-sync: begin marker missing in README.md" >&2; exit 2; }
grep -qF "$END" "$README" || { echo "readme-sync: end marker missing in README.md" >&2; exit 2; }

awk -v b="$BEGIN" -v e="$END" -v f="$block" '
  $0 == b { while ((getline l < f) > 0) print l; skip = 1; next }
  $0 == e { skip = 0; next }
  !skip { print }
' "$README" > "$out"

if [ "${1:-}" = "--check" ]; then
  if cmp -s "$README" "$out"; then echo "  [PASS] README status block matches package.json v$ver + web/SURFACES.tsv"; exit 0; fi
  echo "FAIL: README.md status block is stale; run: sh scripts/readme-sync.sh" >&2
  diff "$README" "$out" >&2 || true
  exit 1
fi
cmp -s "$README" "$out" || cat "$out" > "$README"
echo "readme-sync: README.md at v$ver"
